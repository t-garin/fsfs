function api_page_names(path::String)::Vector{String}
    names = String[]
    seen = Set{String}()
    for line in eachline(path)
        m = match(r"^function\s+([A-Za-z_][A-Za-z0-9_!]*)\s*\(", line)
        m === nothing &&
            (m = match(r"^(?:Agents\.)?@agent\s+struct\s+([A-Za-z_][A-Za-z0-9_]*)", line))
        m === nothing &&
            (m = match(r"^struct\s+([A-Za-z_][A-Za-z0-9_]*)", line))
        if m !== nothing
            name = m.captures[1]
            name in seen || (push!(names, name); push!(seen, name))
        end
    end
    return names
end

function generate_api_pages(source_dir::String, out_dir::String)
    mkpath(out_dir)
    for path in sort(readdir(source_dir; join = true))
        endswith(path, ".jl") || continue
        basename(path) == "FSFS.jl" && continue
        page = joinpath(out_dir, replace(basename(path), ".jl" => ".md"))
        open(page, "w") do io
            println(io, "# `", basename(path), "`")
            println(io)
            println(io, "```@docs")
            for name in api_page_names(path)
                println(io, "FSFS.", name)
            end
            println(io, "```")
        end
    end
    return nothing
end

